#!/usr/bin/env python3
"""The lint's world handle, generated: every `w:` method, answering nothing.

`arc.rules.world` is the whole composition, and the lint runs it against a
handle of its own.  That handle has to carry EVERY method the real one
does, or the rule stops at the first name it cannot find.  Hand-listed,
it drifted: a method the handle had was gone from the pipeline, and a
method the pipeline had was missing from the handle.

So the list comes from `WORLD[]` in `src/script/api_object.c`, which is
the one place a method is registered.  What each answers is read off the
accessor's own pushes.  The generated answer is the EMPTY one of its
type: nought for a number, false for a boolean, nothing for a string, a
table or a handle.  A stub that says "there is none" walks less of the
composition, and it can never make a loop that does not end.

`lint.c` says what must answer otherwise, and every one of those is
there to open a pass or to name a family.

    python3 tools/gen_lint_stub.py            # write the header
    python3 tools/gen_lint_stub.py --check    # is it fresh
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
#  The object layer, whole: WORLD[] and its accessors are in the file
#  that knows the build, and a shared helper may be in another.
SRC = sorted(glob.glob(os.path.join(ROOT, "src", "script", "api_object.c"))
             + glob.glob(os.path.join(ROOT, "src", "script", "obj_*.c"))
             + glob.glob(os.path.join(ROOT, "src", "script", "api_tile.c")))
OUT = os.path.join(ROOT, "src", "script", "generated", "lint_stub.h")
TABLE = "WORLD"

#  What a push puts on the stack, and what the lint's own handle answers
#  in its place.  A number is nought so a count still drives a loop.  A
#  boolean is false so a loop that asks "is there another" ends.
EMPTY = {
    "integer": "0",
    "number": "0",
    "boolean": "false",
    "string": "nil",
    "lstring": "nil",
    "literal": "nil",
    "fstring": "nil",
    "nil": "nil",
    "value": "nil",
    "cclosure": "nil",
    "lightuserdata": "nil",
}

TOKEN = re.compile(r"""
    (?P<newtable>lua_(?:newtable|createtable)\(L\b)
  | (?P<obj>\w+_push\(L\b)
  | lua_push(?P<push>integer|number|string|lstring|boolean|nil|value|literal|fstring|cclosure|lightuserdata)\(L\b
  | (?P<set>lua_(?:setfield|rawseti|seti|setmetatable)\(L\b)
  | (?P<set2>lua_(?:rawset|settable)\(L\b)
  | lua_pop\(L,\s*(?P<pop>\d+)\)
  | return\s+(?P<tail>\w+)\(L\s*[,)]
  | return\s+(?P<ret>\d+)\s*;
""", re.X)


def strip_comments(text):
    return re.sub(r"/\*.*?\*/", " ", text, flags=re.S)


def body_of(src, fn):
    """The braces of `static int fn(lua_State *L)`, comments gone."""
    m = re.search(r"static int " + re.escape(fn) + r"\(lua_State \*L[^)]*\)\s*\{", src)
    if not m:
        return None
    depth, i = 1, m.end()
    while i < len(src) and depth:
        depth += {"{": 1, "}": -1}.get(src[i], 0)
        i += 1
    return strip_comments(src[m.end():i - 1])


def answer(src, fn, seen=()):
    """What the accessor leaves on the stack where it answers most.

    The stack is walked, so a table built field by field counts as one
    value rather than as its fields.  A call whose name ends in _push
    puts ONE handle on the stack, whichever file it is in.  An accessor
    that is one call to a shared helper is followed into it."""
    body = body_of(src, fn)
    if body is None or fn in seen:
        return []
    stack, best = [], []
    for m in TOKEN.finditer(body):
        k = m.lastgroup
        if k == "newtable" or k == "obj":
            stack.append("nil")
        elif k == "push":
            stack.append(EMPTY[m.group("push")])
        elif k == "set":
            if stack:
                stack.pop()
        elif k == "set2":
            del stack[len(stack) - 2:]
        elif k == "pop":
            del stack[len(stack) - int(m.group("pop")):]
        elif k == "tail":
            got = answer(src, m.group("tail"), seen + (fn,))
            if len(got) > len(best):
                best = got
        elif k == "ret":
            n = int(m.group("ret"))
            got = stack[-n:] if n else []
            if len(got) == n and n >= len(best):
                best = got
    return best


def build():
    src = strip_comments("\n".join(open(f).read() for f in SRC))
    m = re.search(r"(?:static )?const luaL_Reg " + TABLE + r"\[\]\s*=\s*\{(.*?)\n\};", src, re.S)
    if not m:
        raise SystemExit("gen_lint_stub: no %s[] in the object layer" % TABLE)
    rows = re.findall(r'\{\s*"(\w+)"\s*,\s*(\w+)\s*\}', m.group(1))
    if not rows:
        raise SystemExit("gen_lint_stub: %s[] is empty" % TABLE)
    out = [
        "/*  lint_stub.h: the lint's world handle, one line a method.",
        " *",
        " *  Generated by tools/gen_lint_stub.py from WORLD[] in",
        " *  api_object.c.  Do not edit: edit the generator.",
        " *",
        " *  Each method answers the EMPTY value of what the real accessor",
        " *  pushes.  lint.c writes over the ones that must answer",
        " *  otherwise, and says why.  So a method added to the pipeline",
        " *  is on the lint's handle with no edit at all. */",
        "#ifndef ARC_LINT_STUB_H",
        "#define ARC_LINT_STUB_H",
        "",
        "#define LINT_WORLD_STUB \\",
    ]
    for name, fn in rows:
        got = answer(src, fn)
        body = " return " + ", ".join(got) + " " if got else " "
        out.append('    "%s = function ()%send," \\' % (name, body))
    out[-1] = out[-1][:-2]
    out += ["", "#endif /* ARC_LINT_STUB_H */", ""]
    return "\n".join(out)


def main():
    text = build()
    if "--check" in sys.argv:
        try:
            have = open(OUT).read()
        except OSError:
            have = None
        if have != text:
            print("gen_lint_stub: %s is stale; run tools/gen_lint_stub.py" % OUT)
            return 1
        print("gen_lint_stub: the lint's world handle is fresh")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(text)
    print("gen_lint_stub: %d methods -> %s" % (text.count("= function"), OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
