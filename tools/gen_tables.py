gen_ordinance.emit(w)
gen_walk.emit(w)

path = os.path.join(os.path.dirname(__file__), "..", "src", "sim", "generated", "tables.c")
text = "\n".join(x for x in out if x is not None) + "\n"

# the generated file is held to the same style as the hand-written ones,
# so `ctest` does not fail the moment the tables are regenerated.  It is
# applied to the TEXT, not to the file, so --check compares what would be
# written rather than what the writer would leave.
import shutil, subprocess
cf = shutil.which("clang-format") or "/opt/homebrew/bin/clang-format"
if os.path.exists(cf):
    r = subprocess.run([cf, "-assume-filename=tables.c"], input=text,
                       capture_output=True, text=True)
    if r.returncode == 0:
        text = r.stdout

#  --check: is the file in the tree already what the A5 image says?  A
#  generated file that is edited by hand, or left behind when its
#  generator moves, is a table that has drifted from its one source.
if "--check" in sys.argv:
    try:
        have = open(path).read()
    except OSError:
        have = None
    if have != text:
        print("src/sim/generated/tables.c is not what the A5 image says; "
              "run tools/gen_tables.py", file=sys.stderr)
        sys.exit(1)
    print("gen_tables: src/sim/generated/tables.c is fresh")
    sys.exit(0)

open(path, "w").write(text)
print("wrote", os.path.normpath(path), len(out), "lines")
