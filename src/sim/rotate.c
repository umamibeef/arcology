/*  One turn of an n x n layer of `stride`-byte cells, through a table
 *  when the layer has one. */
static void rotate_layer(uint8_t *buf, int n, const uint8_t *table, int stride)
{
    static uint8_t tmp[MAP_H * MAP_W * 2];
    int            x, y;
    memcpy(tmp, buf, (size_t)(n * n * stride));
    for (y = 0; y < n; ++y)
        for (x = 0; x < n; ++x)
        {
            int sy = n - 1 - x, sx = y;
            int s = (sy * n + sx) * stride, d = (y * n + x) * stride;
            if (table)
                buf[d] = table[tmp[s]];
            else
                memcpy(buf + d, tmp + s, (size_t)stride);
        }
}

/*  One XTHG record, 12 bytes ($3B96E).  +3 is y and +4 is x; the pair
 *  rotates like every other coordinate, new = (127 - y, x).  Types 10
 *  to 13 carry a four-direction heading, everything else an eight; type
 *  1 alone also turns the nibble at +2. */
void sim_rotate_thing(uint8_t *r)
{
    uint8_t t = r[0], y;
    if (t == 0)
        return;
    y    = r[3];
    r[3] = r[4];
    r[4] = (uint8_t)((127 - y) & 0xFF);
    if (t >= 10 && t <= 13)
    {
        r[1] = (uint8_t)((r[1] - 1) & 3);
        r[8] = (uint8_t)((r[8] - 2) & 7);
        return;
    }
    r[1] = (uint8_t)((r[1] - 2) & 7);
    y    = r[8];
    r[8] = r[9];
    r[9] = (uint8_t)((127 - y) & 0xFF);
    if (t == 1)
        r[2] = (uint8_t)(((((r[2] >> 4) - 2) & 7) << 4) | (r[2] & 0x0F));
}

/*  The art tables, for a renderer choosing the art of a turned view
 *  without turning anything: 0 XBLD, 1 XTER, 2 XUND. */
const uint8_t *sim_rot_table(int layer)
{
    return layer == 0 ? ROT_XBLD : layer == 1 ? ROT_XTER
                                              : ROT_XUND;
}

/*  The city turned a quarter clockwise, as the original's rotate does;
 *  `turns` of them, so 3 is anticlockwise.  This REWRITES the map, as
 *  the original's own Rotate command does; the game's view of a turn
 *  does not use it (see adapt_city_turned): it is here for --rotate. */
void sim_rotate(City *c, int turns)
{
    int k;
    turns &= 3;
    for (k = 0; k < turns; ++k)
    {
        size_t i;
        rotate_layer((uint8_t *)c->altm, MAP_W, NULL, 2);
        rotate_layer(&c->xbld[0][0], MAP_W, ROT_XBLD, 1);
        rotate_layer(&c->xzon[0][0], MAP_W, NULL, 1);
        rotate_layer(&c->xter[0][0], MAP_W, ROT_XTER, 1);
        rotate_layer(&c->xund[0][0], MAP_W, ROT_XUND, 1);
        rotate_layer(&c->xtxt[0][0], MAP_W, NULL, 1);
        rotate_layer(&c->xbit[0][0], MAP_W, NULL, 1);
        rotate_layer(&c->xtrf[0][0], HALF_W, NULL, 1);
        rotate_layer(&c->xplt[0][0], HALF_W, NULL, 1);
        rotate_layer(&c->xval[0][0], HALF_W, NULL, 1);
        rotate_layer(&c->xcrm[0][0], HALF_W, NULL, 1);
        rotate_layer(&c->xplc[0][0], QTR_W, NULL, 1);
        rotate_layer(&c->xfir[0][0], QTR_W, NULL, 1);
        rotate_layer(&c->xpop[0][0], QTR_W, NULL, 1);
        rotate_layer(&c->xrog[0][0], QTR_W, NULL, 1);
        if (c->xthg)
            for (i = 0; i + 12 <= c->xthg_len; i += 12)
                sim_rotate_thing(c->xthg + i);
        c->rotation = (int16_t)((c->rotation + 1) & 3);
    }
}
